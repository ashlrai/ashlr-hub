#!/usr/bin/env node
/**
 * scripts/build-sea.mjs — Bun single-executable build for the Tauri sidecar.
 *
 * What it does:
 *   1. Runs `npm run build`, or freshly verifies explicitly adopted CI bytes.
 *   2. Writes a thin shim entry (dist-bin/_entry.js) that sets
 *      ASHLR_WEB_PUBLIC to the sibling `public/` dir before importing the CLI.
 *      This means the compiled binary self-configures the asset path at runtime
 *      without any external launcher wrapper needed.
 *   3. Writes sibling worker shims (read projections, engineering, fleet
 *      history) with the same build identity, then compiles every entrypoint
 *      → dist-bin/ashlr via `bun build --compile`.
 *   4. Copies dist/core/web/public/ → dist-bin/public/ so the binary and its
 *      assets are co-located.
 *
 * Usage:
 *   node scripts/build-sea.mjs
 *   # or: npm run build:binary
 *   # Verified CI reuse: see docs/RELEASING.md#qualified-ci-build-handoff.
 *
 * Output:
 *   dist-bin/ashlr          — self-contained native binary (~10–15 MB)
 *   dist-bin/public/        — SPA assets (index.html, app.js, styles.css)
 *
 * The binary sets ASHLR_WEB_PUBLIC automatically — no env var needed when
 * launching directly.  When run via Tauri sidecar, the env is also injected
 * by main.rs as a belt-and-suspenders measure.
 *
 * Requirements: Bun >= 1.x on PATH (or at ASHLR_BUN_PATH).
 */

import { execSync, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createBuildIdentity, javascriptStringLiteral } from './build-identity.mjs';
import { validateAdoptedArtifact, verifyArtifact } from './hosted-build-artifact.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(join(here, '..'));
const distBin = join(repoRoot, 'dist-bin');
const distWeb = join(repoRoot, 'dist', 'core', 'web', 'public');
const entry   = join(distBin, '_entry.js');
const workerEntry = join(distBin, 'read-projection-worker.js');
const engineeringWorkerEntry = join(distBin, 'engineering-background-worker.js');
const engineeringReadWorkerEntry = join(distBin, 'engineering-successor-read-worker.js');
// V3.10: fleet-history.ts resolves `./fleet-history-worker.js` next to the main
// entry, like read-projections.ts does. Without this sibling the bundled
// binary cannot start the worker and runs the scorecard snapshot inline
// (~1.6 s blocking once a day).
const fleetHistoryWorkerEntry = join(distBin, 'fleet-history-worker.js');
const outcomesWorkerEntry = join(distBin, 'outcomes-worker.js');
const outBin  = join(distBin, process.platform === 'win32' ? 'ashlr.exe' : 'ashlr');
const pubDest = join(distBin, 'public');
const buildIdentityPath = join(repoRoot, 'dist', 'build-identity.json');

/**
 * V3.10 (review finding c13): the operand-free flag on which the compiled
 * binary re-enters itself to run the scorecard-history custody helper. MUST
 * equal SCORECARD_HISTORY_HELPER_FLAG in src/core/fleet/scorecard-history.ts
 * (test/scorecard-history-sea-310.test.ts pins them together).
 */
export const SCORECARD_HISTORY_HELPER_FLAG = '--_scorecard-history-helper';

// Closed source inventory for the native read-only structural diagnostic.
// Pinned against the runtime reader by the build/safety tests.
export const VERIFY_SAFETY_SOURCE_KEYS = Object.freeze([
  'sandbox/policy', 'daemon/loop', 'knowledge/index', 'knowledge/graph', 'run/provider-client',
]);

export function collectVerifySafetySources({ coreRoot, buildIdentityJson }) {
  const sources = {};
  for (const key of VERIFY_SAFETY_SOURCE_KEYS) {
    const text = readFileSync(join(coreRoot, `${key}.js`), 'utf8');
    if (!text) throw new Error(`Empty native safety source: ${key}`);
    sources[key] = { text, sha256: createHash('sha256').update(text, 'utf8').digest('hex') };
  }
  return JSON.stringify({ schemaVersion: 1, buildIdentityJson, sources });
}

/** Exact source-owned tool worker snapshot; never an account/authority proof. */
export function collectClaudeToolWorkerSource({ coreRoot, buildIdentityJson }) {
  const text = readFileSync(join(coreRoot, 'sandbox/claude-broker-tool-worker.js'), 'utf8');
  if (!text || Buffer.byteLength(text) > 128 * 1024) throw new Error('Invalid native Claude tool worker source');
  return JSON.stringify({ schemaVersion: 1, buildIdentityJson, text,
    sha256: createHash('sha256').update(text, 'utf8').digest('hex') });
}

export function createSeaShim({ pkgVersion, buildIdentityJson, verifySafetySourcesJson, claudeToolWorkerSourceJson, desktopPairIdentityJson }) {
  return `// Auto-generated by scripts/build-sea.mjs — do not edit manually.
// Sets ASHLR_WEB_PUBLIC and ASHLR_VERSION before the CLI boots so that:
//   - assetsDir() finds the SPA assets next to this compiled binary.
//   - --version works without reading ../../package.json from the virtual FS.
//
// NOTE: Inside a Bun-compiled binary, import.meta.dir resolves to the virtual
// FS path (/$bunfs/root/…), NOT the real filesystem location of the binary.
// process.execPath IS the real path to the binary — use dirname() on that.
import { dirname } from 'node:path';
// Scorecard history's one-shot custody helper is a CHILD PROCESS (its cwd is
// the pinned history directory — a Worker thread cannot chdir), and inside
// this binary it has no on-disk script to spawn. scorecard-history.ts
// therefore re-executes this binary with exactly one fixed, operand-free
// flag, dispatched here to the same helper script compiled in. The flag must
// be the ENTIRE argv; it carries no path or module specifier, and the helper
// validates its stdin request (pinned root identity) before any file access.
if (process.argv.length === 3 && process.argv[2] === ${JSON.stringify(SCORECARD_HISTORY_HELPER_FLAG)}) {
  await import('../scripts/scorecard-history-worker.mjs');
} else {
if (!process.env.ASHLR_WEB_PUBLIC) {
  process.env.ASHLR_WEB_PUBLIC = dirname(process.execPath) + '/public';
}
if (!process.env.ASHLR_VERSION) {
  process.env.ASHLR_VERSION = ${JSON.stringify(pkgVersion)};
}
Reflect.set(
  globalThis,
  Symbol.for('ashlr.build-identity.v1'),
  ${javascriptStringLiteral(buildIdentityJson)},
);
${desktopPairIdentityJson === undefined ? '' : `Reflect.set(globalThis, Symbol.for('phantom.desktop-pair-build.v1'), ${javascriptStringLiteral(desktopPairIdentityJson)});`}
${verifySafetySourcesJson === undefined ? '' : `Reflect.set(globalThis, Symbol.for('ashlr.verify-safety-sources.v1'), ${javascriptStringLiteral(verifySafetySourcesJson)});`}
${claudeToolWorkerSourceJson === undefined ? '' : `Reflect.set(globalThis, Symbol.for('ashlr.claude-tool-worker-source.v1'), ${javascriptStringLiteral(claudeToolWorkerSourceJson)});`}
await import('../dist/cli/index.js');
}
`;
}

