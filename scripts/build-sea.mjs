/**
 * @param {{ entry: string, workerEntry: string, engineeringWorkerEntry?: string,
 *   engineeringReadWorkerEntry?: string, fleetHistoryWorkerEntry?: string, outcomesWorkerEntry?: string, outBin: string }} args
 */
export function createSeaCompileArgs({
  entry, workerEntry, engineeringWorkerEntry, engineeringReadWorkerEntry, fleetHistoryWorkerEntry, outcomesWorkerEntry, outBin,
}) {
  // Bun does not discover Worker URLs automatically. All shims must be
  // siblings: bundled import.meta.url resolves relative to the main entry.
  return ['build', '--compile', entry, workerEntry, ...(engineeringWorkerEntry ? [engineeringWorkerEntry] : []),
    ...(engineeringReadWorkerEntry ? [engineeringReadWorkerEntry] : []),
    ...(fleetHistoryWorkerEntry ? [fleetHistoryWorkerEntry] : []), ...(outcomesWorkerEntry ? [outcomesWorkerEntry] : []), '--outfile', outBin];
}

export function parseHostedBuildArguments(args) {
  if (args.length === 0) return null;
  const allowed = ['--hosted-bundle', '--run', '--attempt', '--attestor-sha', '--attestor-run', '--attestor-attempt'];
  const flags = {};
  for (let i = 0; i < args.length; i += 2) {
    if (!allowed.includes(args[i]) || typeof args[i + 1] !== 'string' || !args[i + 1] || Object.hasOwn(flags, args[i])) throw new Error('Invalid hosted build arguments');
    flags[args[i]] = args[i + 1];
  }
  if (allowed.some((key) => !Object.hasOwn(flags, key)) || !isAbsolute(flags['--hosted-bundle']) || !/^[a-f0-9]{40}$/.test(flags['--attestor-sha'])) throw new Error('Complete hosted build identity required');
  for (const key of ['--run', '--attempt', '--attestor-run', '--attestor-attempt']) {
    if (!/^[1-9][0-9]*$/.test(flags[key]) || !Number.isSafeInteger(Number(flags[key]))) throw new Error('Invalid hosted run identity');
  }
  return { bundle: flags['--hosted-bundle'], runId: Number(flags['--run']), runAttempt: Number(flags['--attempt']),
    attestorSha: flags['--attestor-sha'], attestorRun: Number(flags['--attestor-run']), attestorAttempt: Number(flags['--attestor-attempt']) };
}

export function ensureSeaBuild({ args, root, build = () => execSync('npm run build', { cwd: root, stdio: 'inherit' }),
  identity = createBuildIdentity, verify = verifyArtifact, validate = validateAdoptedArtifact }) {
  const hosted = parseHostedBuildArguments(args);
  if (!hosted) { build(); return { mode: 'local' }; }
  const current = identity({ repoRoot: root });
  if (current.provenance !== 'git' || current.dirty !== false || !current.revision) throw new Error('Clean source identity required for hosted native build');
  const { bundle, ...policy } = hosted;
  const receipt = verify({ root, revision: current.revision, bundle, policy });
  validate(receipt);
  return { mode: 'hosted', receipt };
}

async function main() {
parseHostedBuildArguments(process.argv.slice(2));

// ── locate bun ───────────────────────────────────────────────────────────────
const BUN = process.env.ASHLR_BUN_PATH ??
  (() => {
    // Try the standard Bun install location first, then PATH.
    const isWin = process.platform === 'win32';
    const home = process.env.HOME ?? process.env.USERPROFILE ?? '';
    const wellKnown = join(home, '.bun', 'bin', isWin ? 'bun.exe' : 'bun');
    if (existsSync(wellKnown)) return wellKnown;
    try {
      const out = execSync(isWin ? 'where bun' : 'which bun', { encoding: 'utf8' });
      return out.split(/\r?\n/).map((s) => s.trim()).find(Boolean) ?? (isWin ? 'bun.exe' : null);
    } catch {
      return isWin ? 'bun.exe' : null;
    }
  })();

if (!BUN) {
  console.error(
    'ERROR: bun not found. Install via https://bun.sh or set ASHLR_BUN_PATH.',
  );
  process.exit(1);
}
console.log(`[build-sea] Using bun: ${BUN}`);

// ── 1. Ensure dist/ is fresh ─────────────────────────────────────────────────
console.log('[build-sea] Preparing source-bound JavaScript build…');
const prepared = ensureSeaBuild({ args: process.argv.slice(2), root: repoRoot });
console.log(`[build-sea] ${prepared.mode === 'hosted' ? 'Verified adopted CI bytes; native compilation follows' : 'Local npm build complete'}`);

if (!existsSync(distWeb)) {
  console.error(`ERROR: dist/core/web/public not found after build: ${distWeb}`);
  process.exit(1);
}

// ── 2. Write thin shim entry ─────────────────────────────────────────────────
// The shim sets ASHLR_WEB_PUBLIC and ASHLR_VERSION before the CLI boots:
//   ASHLR_WEB_PUBLIC — points to the sibling `public/` dir resolved via
//     import.meta.dir (the directory of the *binary* at runtime in Bun).
//   ASHLR_VERSION — baked in at build time because createRequire cannot reach
//     ../../package.json from inside Bun's virtual FS (/$bunfs/root/…).
//
// Runtime configuration remains caller-overridable, but canonical build
// identity is always the value embedded into this artifact.
mkdirSync(distBin, { recursive: true });

const pkgVersion = JSON.parse(
  readFileSync(join(repoRoot, 'package.json'), 'utf8'),
).version ?? '0.0.0';
const buildIdentityJson = readFileSync(buildIdentityPath, 'utf8').trim();

const verifySafetySourcesJson = collectVerifySafetySources({
  coreRoot: join(repoRoot, 'dist', 'core'), buildIdentityJson,
});
const claudeToolWorkerSourceJson = collectClaudeToolWorkerSource({
  coreRoot: join(repoRoot, 'dist', 'core'), buildIdentityJson,
});
const source = prepared.mode === 'hosted' ? prepared.receipt.source : null;
const desktopPairIdentityJson = source ? JSON.stringify({ schemaVersion: 1, revision: source.revision, tree: source.tree, version: pkgVersion }) : undefined;
const shimSrc = createSeaShim({ pkgVersion, buildIdentityJson, verifySafetySourcesJson, claudeToolWorkerSourceJson, desktopPairIdentityJson });

writeFileSync(entry, shimSrc, 'utf8');
writeFileSync(workerEntry, createSeaWorkerShim({ buildIdentityJson }), 'utf8');
writeFileSync(outcomesWorkerEntry, createSeaOutcomesWorkerShim({ buildIdentityJson }), 'utf8');
writeFileSync(engineeringWorkerEntry, createSeaEngineeringWorkerShim({ buildIdentityJson }), 'utf8');
writeFileSync(engineeringReadWorkerEntry, createSeaEngineeringReadWorkerShim({ buildIdentityJson }), 'utf8');
writeFileSync(fleetHistoryWorkerEntry, createSeaFleetHistoryWorkerShim({ buildIdentityJson }), 'utf8');
console.log(`[build-sea] Wrote shim entry: ${entry}`);

// ── 3. bun build --compile ───────────────────────────────────────────────────
// Remove stale binary first so a partial build doesn't look successful.
if (existsSync(outBin)) rmSync(outBin);

console.log(`[build-sea] Compiling → ${outBin} …`);
const result = spawnSync(
  BUN,
  createSeaCompileArgs({ entry, workerEntry, engineeringWorkerEntry, engineeringReadWorkerEntry, fleetHistoryWorkerEntry, outcomesWorkerEntry, outBin }),
  { cwd: repoRoot, encoding: 'utf8' },
);
if (result.stdout) process.stdout.write(result.stdout);
if (result.status !== 0) {
  console.error(`[build-sea] bun build --compile failed (exit ${result.status}).`);
  if (result.stderr) console.error('[build-sea] bun stderr:\n' + result.stderr);
  if (result.error) console.error('[build-sea] spawn error:', result.error);
  process.exit(result.status ?? 1);
}

// Confirm the binary exists and report size.
const { statSync } = await import('node:fs');
const binStat = statSync(outBin);
const sizeMB  = (binStat.size / 1_048_576).toFixed(1);
console.log(`[build-sea] Binary: ${outBin}  (${sizeMB} MB)`);

// ── 4. Copy SPA assets next to the binary ────────────────────────────────────
if (existsSync(pubDest)) rmSync(pubDest, { recursive: true });
cpSync(distWeb, pubDest, { recursive: true });
console.log(`[build-sea] Assets: ${distWeb} → ${pubDest}`);

console.log('\n[build-sea] Done.');
console.log(`  Binary : ${outBin}`);
console.log(`  Assets : ${pubDest}`);
console.log(`\nSmoke test:`);
console.log(`  ${outBin} --version`);
console.log(`  ASHLR_WEB_PUBLIC=${pubDest} ${outBin} serve &`);
console.log(`  curl -s http://127.0.0.1:7777 | head -5`);
}

const invokedPath = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : '';
if (import.meta.url === invokedPath) {
  await main();
}
