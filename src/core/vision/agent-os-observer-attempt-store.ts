function sameStartBinding(
  receipt: AgentOsObserverAttemptReceiptV1,
  input: AgentOsObserverAttemptStartInputV1,
): boolean {
  return receipt.attemptId === input.attemptId &&
    sameDigest(receipt.initiatingTickDigest, input.initiatingTickDigest) &&
    receipt.initiatingTickAt === input.initiatingTickAt &&
    ((receipt.bundleDigest === null && input.bundleDigest === null) ||
      sameDigest(receipt.bundleDigest, input.bundleDigest)) &&
    receipt.startedAt === input.startedAt && receipt.deadlineAt === input.deadlineAt;
}

function validateTransitions(
  records: readonly AgentOsObserverAttemptReceiptV1[],
): AgentOsObserverAttemptReadStopReasonV1[] {
  const reasons = new Set<AgentOsObserverAttemptReadStopReasonV1>();
  const byAttempt = new Map<string, AgentOsObserverAttemptReceiptV1[]>();
  for (const receipt of records) {
    const current = byAttempt.get(receipt.attemptId) ?? [];
    current.push(receipt);
    byAttempt.set(receipt.attemptId, current);
  }
  for (const attempt of byAttempt.values()) {
    const starts = attempt.filter((receipt) => receipt.transitionOrdinal === 1);
    const terminals = attempt.filter((receipt) => receipt.transitionOrdinal === 2);
    if (starts.length > 1 || terminals.length > 1) reasons.add('transition-fork');
    if (starts.length === 0 && terminals.length > 0) reasons.add('transition-gap');
    if (starts.length !== 1 || terminals.length === 0) continue;
    const start = starts[0]!;
    for (const terminal of terminals) {
      if (!sameStartBinding(terminal, start) || !sameDigest(terminal.previousReceiptDigest, start.receiptDigest)) {
        reasons.add('invalid-transition');
      }
      if (terminal.completedAt === null || Date.parse(terminal.completedAt) < Date.parse(start.startedAt)) {
        reasons.add('non-monotonic-transition');
      }
    }
  }
  return [...reasons];
}

export function readAgentOsObserverAttemptReceiptsV1(
  dependencies: AgentOsObserverAttemptStoreDependenciesV1 | null =
    defaultAgentOsObserverAttemptStoreDependenciesV1('read'),
  options: ImmutablePrivateRecordReadOptions = {},
): AgentOsObserverAttemptReadResultV1 {
  if (!dependencies || !validDependencies(dependencies)) return emptyRead('degraded', ['invalid-options']);
  if (!dependencies.key) return emptyRead('degraded', ['key-unavailable']);
  const raw = readImmutablePrivateRecords(storeConfig(dependencies), { ...options, requireComplete: false });
  if (raw.sourceState === 'missing') {
    return {
      ...raw,
      records: [],
      capacityExhausted: false,
      authority: 'observation-only',
      effectAuthority: 'none',
    };
  }
  const transitionReasons = validateTransitions(raw.records);
  const stopReasons = [...new Set<AgentOsObserverAttemptReadStopReasonV1>([
    ...raw.stopReasons,
    ...transitionReasons,
  ])];
  const degraded = raw.sourceState === 'degraded' || stopReasons.length > 0;
  return {
    ...raw,
    records: degraded && options.requireComplete === true ? [] : raw.records,
    sourceState: degraded ? 'degraded' : 'healthy',
    complete: !degraded,
    stopReasons,
    capacityExhausted: raw.records.length + 2 > recordCapacity(dependencies),
    authority: 'observation-only',
    effectAuthority: 'none',
  };
}

function transitionLockPath(dependencies: AgentOsObserverAttemptStoreDependenciesV1): string {
  return join(dependencies.anchorPath, '.agent-os-observer-attempt-transition.lock');
}

function recordCapacity(dependencies: AgentOsObserverAttemptStoreDependenciesV1): number {
  return dependencies.maxRecords ?? MAX_RECORDS;
}

function writeReceipt(
  receipt: AgentOsObserverAttemptReceiptV1,
  dependencies: AgentOsObserverAttemptStoreDependenciesV1,
  lockWaitMs: number,
): AgentOsObserverAttemptWriteResultV1 {
  const disposition = writeImmutablePrivateRecord(storeConfig(dependencies), receipt, { lockWaitMs });
  if (disposition === 'recorded' || disposition === 'replayed') return { disposition, receipt };
  return {
    disposition: disposition === 'conflicted' ? 'conflicted' :
      disposition === 'invalid' ? 'invalid' : 'persistence-failed',
    receipt: null,
  };
}

function boundedLockWait(value: number | undefined): number | null {
  if (value === undefined) return MAX_LOCK_WAIT_MS;
  return Number.isFinite(value) ? Math.max(0, Math.min(MAX_LOCK_WAIT_MS, Math.floor(value))) : null;
}

export function beginAgentOsObserverAttemptV1(
  input: AgentOsObserverAttemptStartInputV1,
  dependencies: AgentOsObserverAttemptStoreDependenciesV1 | null =
    defaultAgentOsObserverAttemptStoreDependenciesV1('write'),
  options: { lockWaitMs?: number } = {},
): AgentOsObserverAttemptWriteResultV1 {
  if (!validStartInput(input)) return { disposition: 'invalid', receipt: null };
  if (!dependencies || !validDependencies(dependencies)) return { disposition: 'store-unavailable', receipt: null };
  if (!dependencies.key) return { disposition: 'key-unavailable', receipt: null };
  const lockWaitMs = boundedLockWait(options.lockWaitMs);
  if (lockWaitMs === null) return { disposition: 'invalid', receipt: null };
  if (!existsSync(dependencies.anchorPath)) return { disposition: 'store-unavailable', receipt: null };
  const transitionLock = acquireLocalStoreLock(
    transitionLockPath(dependencies),
    lockWaitMs,
    { anchorPath: dependencies.anchorPath, exactPrivateStorage: true },
  );
  if (!transitionLock) return { disposition: 'store-unavailable', receipt: null };
  try {
    const read = readAgentOsObserverAttemptReceiptsV1(dependencies, { requireComplete: true });
    if (read.sourceState === 'degraded') return { disposition: 'store-unavailable', receipt: null };
    const attempt = read.records.filter((receipt) => receipt.attemptId === input.attemptId);
    const existingStart = attempt.find((receipt) => receipt.transitionOrdinal === 1);
    if (existingStart && !sameStartBinding(existingStart, input)) {
      return { disposition: 'conflicted', receipt: null };
    }
    if (read.records.length >= recordCapacity(dependencies) && !existingStart) {
      return { disposition: 'capacity-exhausted', receipt: null };
    }
    return writeReceipt(seal(unsignedStart(input), dependencies.key), dependencies, lockWaitMs);
  } finally {
    releaseLocalStoreLock(transitionLock);
  }
}

export function completeAgentOsObserverAttemptV1(
  input: AgentOsObserverAttemptTerminalInputV1,
  dependencies: AgentOsObserverAttemptStoreDependenciesV1 | null =
    defaultAgentOsObserverAttemptStoreDependenciesV1('write'),
  options: { lockWaitMs?: number } = {},
): AgentOsObserverAttemptWriteResultV1 {
  if (!validTerminalInput(input)) return { disposition: 'invalid', receipt: null };
  if (!dependencies || !validDependencies(dependencies)) return { disposition: 'store-unavailable', receipt: null };
  if (!dependencies.key) return { disposition: 'key-unavailable', receipt: null };
  const lockWaitMs = boundedLockWait(options.lockWaitMs);
  if (lockWaitMs === null) return { disposition: 'invalid', receipt: null };
  if (!existsSync(dependencies.anchorPath)) return { disposition: 'store-unavailable', receipt: null };
  const transitionLock = acquireLocalStoreLock(
    transitionLockPath(dependencies),
    lockWaitMs,
    { anchorPath: dependencies.anchorPath, exactPrivateStorage: true },
  );
  if (!transitionLock) return { disposition: 'store-unavailable', receipt: null };
  try {
    const read = readAgentOsObserverAttemptReceiptsV1(dependencies, { requireComplete: true });
    if (read.sourceState === 'degraded') return { disposition: 'store-unavailable', receipt: null };
    const attempt = read.records.filter((receipt) => receipt.attemptId === input.attemptId);
    const starts = attempt.filter((receipt) => receipt.transitionOrdinal === 1);
    const terminals = attempt.filter((receipt) => receipt.transitionOrdinal === 2);
    if (starts.length !== 1 || !sameStartBinding(starts[0]!, input)) {
      return { disposition: 'invalid-transition', receipt: null };
    }
    const candidate = seal(unsignedTerminal(input, starts[0]!), dependencies.key);
    if (terminals.length > 0) {
      return terminals.length === 1 && sameDigest(terminals[0]!.receiptDigest, candidate.receiptDigest)
        ? writeReceipt(candidate, dependencies, lockWaitMs)
        : { disposition: 'conflicted', receipt: null };
    }
    if (read.records.length >= recordCapacity(dependencies)) {
      return { disposition: 'capacity-exhausted', receipt: null };
    }
    return writeReceipt(candidate, dependencies, lockWaitMs);
  } finally {
    releaseLocalStoreLock(transitionLock);
  }
}

