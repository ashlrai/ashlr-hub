function seal(unsigned: UnsignedReceipt, key: Buffer): AgentOsObserverAttemptReceiptV1 {
  const receiptDigest = sha('ashlr:agent-os-observer-attempt:receipt:v1', unsigned);
  const attestation = hmac(key, 'ashlr:agent-os-observer-attempt:attestation:v1', [
    receiptDigest,
    unsigned.attemptId,
    unsigned.transitionOrdinal,
  ]);
  return { ...unsigned, receiptDigest, attestation };
}

function reconstructWithKey(value: unknown, key: Buffer): AgentOsObserverAttemptReceiptV1 | null {
  const row = recordOf(value);
  if (key.length !== 32 || !row || !exactKeys(row, RECEIPT_KEYS) || row['schemaVersion'] !== 1 ||
    row['protocol'] !== PROTOCOL || row['recordType'] !== RECORD_TYPE ||
    row['authority'] !== 'observation-only' || row['effectAuthority'] !== 'none' ||
    row['planningAuthority'] !== false || row['executionAuthority'] !== false ||
    row['proposalAuthority'] !== false || row['mergeAuthority'] !== false ||
    row['releaseAuthority'] !== false || row['deployAuthority'] !== false ||
    row['publicationAuthority'] !== false || row['externalMutationAuthority'] !== false ||
    row['learningAuthority'] !== false || row['policyEligible'] !== false ||
    row['sameUserTamperResistant'] !== false || row['rollbackProtected'] !== false ||
    row['historicalAuthority'] !== false || row['attestationAuthority'] !== 'host-shared-hmac' ||
    row['verifierIsolated'] !== false || typeof row['attemptId'] !== 'string' ||
    !UUID_V4_RE.test(row['attemptId']) || !plainDigest(row['initiatingTickDigest']) ||
    !canonicalTimestamp(row['initiatingTickAt']) || !canonicalTimestamp(row['startedAt']) ||
    !canonicalTimestamp(row['deadlineAt']) || !plainDigest(row['previousReceiptDigest']) ||
    !plainDigest(row['receiptDigest']) || !plainDigest(row['attestation'])) return null;

  const phase = row['phase'];
  const ordinal = row['transitionOrdinal'];
  const startedShape = ordinal === 1 && phase === 'started' && row['terminalOutcome'] === null &&
    (row['bundleDigest'] === null || digest(row['bundleDigest'])) &&
    row['snapshotDigest'] === null && row['snapshotEnvelopeDigest'] === null &&
    row['snapshotEnvelopeSequence'] === null && row['completedAt'] === null &&
    row['previousReceiptDigest'] === GENESIS_DIGEST;
  const terminalShape = ordinal === 2 && phase === 'terminal' &&
    typeof row['terminalOutcome'] === 'string' && TERMINAL_OUTCOMES.has(row['terminalOutcome'] as AgentOsObserverTerminalOutcomeV1) &&
    canonicalTimestamp(row['completedAt']);
  if (!startedShape && !terminalShape) return null;

  const unsigned = { ...row } as Record<string, unknown>;
  delete unsigned['receiptDigest'];
  delete unsigned['attestation'];
  const receiptDigest = sha('ashlr:agent-os-observer-attempt:receipt:v1', unsigned);
  const attestation = hmac(key, 'ashlr:agent-os-observer-attempt:attestation:v1', [
    receiptDigest,
    row['attemptId'],
    ordinal,
  ]);
  if (!sameDigest(row['receiptDigest'], receiptDigest) || !sameDigest(row['attestation'], attestation)) return null;

  const receipt = row as unknown as AgentOsObserverAttemptReceiptV1;
  const startLike = {
    attemptId: receipt.attemptId,
    initiatingTickDigest: receipt.initiatingTickDigest,
    initiatingTickAt: receipt.initiatingTickAt,
    bundleDigest: receipt.bundleDigest,
    startedAt: receipt.startedAt,
    deadlineAt: receipt.deadlineAt,
  };
  if (!validStartInput(startLike)) return null;
  if (receipt.phase === 'terminal') {
    if (!validTerminalInput({
      ...startLike,
      outcome: receipt.terminalOutcome!,
      bundleDigest: receipt.bundleDigest,
      snapshotDigest: receipt.snapshotDigest,
      snapshotEnvelopeDigest: receipt.snapshotEnvelopeDigest,
      snapshotEnvelopeSequence: receipt.snapshotEnvelopeSequence,
      completedAt: receipt.completedAt!,
    })) return null;
  }
  return { ...receipt };
}

function receiptCodec(key: Buffer): ImmutablePrivateRecordCodec<AgentOsObserverAttemptReceiptV1> {
  return {
    parse: (value) => reconstructWithKey(value, key),
    serialize: (receipt) => `${JSON.stringify(receipt)}\n`,
    recordId: (receipt) => receipt.receiptDigest,
    recordFileName: (receipt) =>
      `${receipt.attemptId}.${receipt.transitionOrdinal}.${receipt.receiptDigest}.json`,
    isRecordFileName: (fileName) => RECORD_FILE_RE.test(fileName),
    stageToken: (receipt) => hmac(
      key,
      'ashlr:agent-os-observer-attempt:publication-stage:v1',
      receipt.receiptDigest,
    ).slice(0, 32),
    equivalent: (left, right) => sameDigest(left.receiptDigest, right.receiptDigest) &&
      sameDigest(left.attestation, right.attestation),
    compare: (left, right) => left.attemptId.localeCompare(right.attemptId) ||
      left.transitionOrdinal - right.transitionOrdinal ||
      left.receiptDigest.localeCompare(right.receiptDigest),
  };
}

