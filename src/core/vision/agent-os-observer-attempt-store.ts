function recordOf(value: unknown): Record<string, unknown> | null {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) return null;
  try {
    const prototype = Object.getPrototypeOf(value);
    if (prototype !== Object.prototype && prototype !== null) return null;
    const keys = Reflect.ownKeys(value);
    if (keys.some((key) => typeof key !== 'string')) return null;
    const descriptors = Object.getOwnPropertyDescriptors(value);
    if (keys.some((key) => {
      const descriptor = descriptors[String(key)];
      return !descriptor?.enumerable || !('value' in descriptor);
    })) return null;
    return value as Record<string, unknown>;
  } catch {
    return null;
  }
}

function exactKeys(value: Record<string, unknown>, expected: ReadonlySet<string>): boolean {
  const keys = Object.keys(value);
  return keys.length === expected.size && keys.every((key) => expected.has(key));
}

function canonicalTimestamp(value: unknown): value is string {
  if (typeof value !== 'string' || value.length > 40) return false;
  const milliseconds = Date.parse(value);
  return Number.isFinite(milliseconds) && new Date(milliseconds).toISOString() === value;
}

function digest(value: unknown): value is string {
  return typeof value === 'string' && SHA256_RE.test(value);
}

function plainDigest(value: unknown): value is string {
  return typeof value === 'string' && PLAIN_SHA256_RE.test(value);
}

function sameDigest(left: unknown, right: unknown): boolean {
  if (!digest(left) || !digest(right)) return false;
  const normalizedLeft = left.replace(/^sha256:/u, '');
  const normalizedRight = right.replace(/^sha256:/u, '');
  const first = Buffer.from(normalizedLeft, 'hex');
  const second = Buffer.from(normalizedRight, 'hex');
  return first.length === second.length && timingSafeEqual(first, second);
}

function sha(domain: string, value: unknown): string {
  return createHash('sha256').update(JSON.stringify([domain, value]), 'utf8').digest('hex');
}

function hmac(key: Buffer, domain: string, value: unknown): string {
  return createHmac('sha256', key).update(JSON.stringify([domain, value]), 'utf8').digest('hex');
}

function validDependencies(value: AgentOsObserverAttemptStoreDependenciesV1): boolean {
  try {
    const anchor = resolve(value.anchorPath);
    const root = resolve(value.rootPath);
    return value.anchorPath === anchor && value.rootPath === root && isAbsolute(anchor) && isAbsolute(root) &&
      anchor !== parse(anchor).root && root !== anchor && dirname(root) === anchor &&
      (value.key === null || (Buffer.isBuffer(value.key) && value.key.length === 32)) &&
      (value.maxRecords === undefined ||
        (Number.isSafeInteger(value.maxRecords) && value.maxRecords >= 2 && value.maxRecords <= MAX_RECORDS));
  } catch {
    return false;
  }
}

function validStartInput(value: unknown): value is AgentOsObserverAttemptStartInputV1 {
  const row = recordOf(value);
  if (!row || !exactKeys(row, START_INPUT_KEYS)) return false;
  const input = value as AgentOsObserverAttemptStartInputV1;
  if (!UUID_V4_RE.test(input.attemptId) || !plainDigest(input.initiatingTickDigest) ||
    !canonicalTimestamp(input.initiatingTickAt) || !canonicalTimestamp(input.startedAt) ||
    !canonicalTimestamp(input.deadlineAt) ||
    (input.bundleDigest !== null && !digest(input.bundleDigest))) return false;
  const tickAt = Date.parse(input.initiatingTickAt);
  const startedAt = Date.parse(input.startedAt);
  const deadlineAt = Date.parse(input.deadlineAt);
  return tickAt <= startedAt && startedAt < deadlineAt;
}

function validTerminalBindings(input: AgentOsObserverAttemptTerminalInputV1): boolean {
  const bundle = input.bundleDigest;
  const snapshot = input.snapshotDigest;
  const envelope = input.snapshotEnvelopeDigest;
  const sequence = input.snapshotEnvelopeSequence;
  const noSnapshotEnvelope = envelope === null && sequence === null;
  const exactSnapshotEnvelope = plainDigest(envelope) && Number.isSafeInteger(sequence) &&
    Number(sequence) >= 1 && Number(sequence) <= MAX_SNAPSHOT_SEQUENCE;

  if (input.outcome === 'completed' || input.outcome === 'replayed') {
    return digest(bundle) && digest(snapshot) && exactSnapshotEnvelope;
  }
  if (input.outcome === 'append-failed' || input.outcome === 'ambiguous-after-commit') {
    return digest(bundle) && digest(snapshot) && noSnapshotEnvelope;
  }
  if (input.outcome === 'source-incomplete' || input.outcome === 'source-invalid') {
    // A malformed or unavailable source may not carry even a syntactically
    // valid claimed digest. The durable attempt must still close; null here is
    // an explicit absence, never an authenticated source identity.
    return (bundle === null || digest(bundle)) && snapshot === null && noSnapshotEnvelope;
  }
  return (bundle === null || digest(bundle)) && snapshot === null && noSnapshotEnvelope;
}

function validTerminalInput(value: unknown): value is AgentOsObserverAttemptTerminalInputV1 {
  const row = recordOf(value);
  if (!row || !exactKeys(row, TERMINAL_INPUT_KEYS)) return false;
  const input = value as AgentOsObserverAttemptTerminalInputV1;
  if (!TERMINAL_OUTCOMES.has(input.outcome) || !validStartInput({
    attemptId: input.attemptId,
    initiatingTickDigest: input.initiatingTickDigest,
    initiatingTickAt: input.initiatingTickAt,
    bundleDigest: input.bundleDigest,
    startedAt: input.startedAt,
    deadlineAt: input.deadlineAt,
  }) || !canonicalTimestamp(input.completedAt) || Date.parse(input.completedAt) < Date.parse(input.startedAt) ||
    (input.outcome === 'deadline-before-commit' && Date.parse(input.completedAt) < Date.parse(input.deadlineAt)) ||
    ((input.outcome === 'completed' || input.outcome === 'replayed') &&
      Date.parse(input.completedAt) >= Date.parse(input.deadlineAt))) {
    return false;
  }
  return validTerminalBindings(input);
}

