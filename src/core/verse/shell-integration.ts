/** The per-user directory the scripts are written to (never the operator's home). */
export function defaultShellIntegrationDir(): string {
  const uid = typeof process.getuid === 'function' ? process.getuid() : 'user';
  return join(tmpdir(), `ashlr-verse-shell-${uid}`, `v${SHELL_INTEGRATION_VERSION}`);
}

/** Refuse a directory we did not make: a symlink, someone else's, or writable by others. */
async function assertPrivateDir(dir: string): Promise<void> {
  const st = await lstat(dir);
  if (!st.isDirectory() || st.isSymbolicLink()) throw new Error('shell integration dir is not a plain directory');
  if (typeof process.getuid === 'function' && st.uid !== process.getuid()) throw new Error('shell integration dir is not ours');
  if (process.platform !== 'win32' && (st.mode & 0o022) !== 0) throw new Error('shell integration dir is writable by others');
}

async function writeAtomic(path: string, content: string): Promise<void> {
  const temp = `${path}.${randomBytes(4).toString('hex')}.tmp`;
  await writeFile(temp, content, { mode: 0o600 });
  await rename(temp, path);
}

async function fileHas(path: string, content: string): Promise<boolean> {
  try {
    const st = await lstat(path);
    // Same length is enough to skip a rewrite: the directory is versioned and private.
    return st.isFile() && !st.isSymbolicLink() && st.size === Buffer.byteLength(content);
  } catch {
    return false;
  }
}

/** Every file a shell kind needs, keyed by path relative to the integration dir. */
export function integrationFiles(kind: IntegratedShell): Record<string, string> {
  if (kind === 'zsh') {
    return Object.fromEntries(Object.entries(zshIntegrationFiles()).map(([name, body]) => [join('zsh', name), body]));
  }
  if (kind === 'bash') return { 'ashlr-integration.bash': bashIntegrationScript() };
  return { 'ashlr-integration.fish': fishIntegrationScript() };
}

/**
 * Write `kind`'s files under `dir` if they are missing. Async throughout —
 * this runs on a terminal-create request. Throws when the directory is not
 * safe to source from; the caller then starts the shell without integration.
 */
export async function ensureIntegrationFiles(dir: string, kind: IntegratedShell): Promise<void> {
  await mkdir(dir, { recursive: true, mode: 0o700 });
  // The parent too: it is the per-user directory another user could pre-create.
  await assertPrivateDir(join(dir, '..'));
  await assertPrivateDir(dir);
  const files = integrationFiles(kind);
  for (const [rel, body] of Object.entries(files)) {
    const path = join(dir, rel);
    const sub = join(path, '..');
    if (sub !== dir) {
      await mkdir(sub, { recursive: true, mode: 0o700 });
      await assertPrivateDir(sub);
    }
    if (!(await fileHas(path, body))) await writeAtomic(path, body);
  }
}

export interface IntegratedLaunch {
  argv: string[];
  /** Variables to ADD to the shell's environment. */
  env: Record<string, string>;
  kind: IntegratedShell;
}

/** Single-quote for fish (`\\` and `'` are the only escapes inside '…'). */
function fishQuote(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/**
 * How to start `shell` with integration: argv and the variables to add.
 * `userEnv` is the environment the shell would otherwise get (for zsh's own
 * ZDOTDIR). Null when the shell is not one we integrate with.
 */
export function integratedLaunch(shell: string, dir: string, nonce: string, userEnv: Record<string, string>): IntegratedLaunch | null {
  const kind = integratedShellKind(shell);
  if (!kind) return null;
  const env: Record<string, string> = { ASHLR_SHELL_NONCE: nonce };
  if (kind === 'zsh') {
    const userZdotdir = userEnv['ZDOTDIR'];
    if (typeof userZdotdir === 'string' && userZdotdir.length > 0) env['ASHLR_USER_ZDOTDIR'] = userZdotdir;
    env['ZDOTDIR'] = join(dir, 'zsh');
    return { argv: [shell, '-l'], env, kind };
  }
  if (kind === 'bash') {
    return { argv: [shell, '--init-file', join(dir, 'ashlr-integration.bash')], env, kind };
  }
  return { argv: [shell, '-l', '--init-command', `source ${fishQuote(join(dir, 'ashlr-integration.fish'))}`], env, kind };
}

/** A fresh per-tab nonce (hex; never contains ';' or control characters). */
export function newShellNonce(): string {
  return randomBytes(12).toString('hex');
}

// ---------------------------------------------------------------------------
// Parsing the marks
// ---------------------------------------------------------------------------

export type ShellMark =
  | { kind: 'prompt-start' }
  | { kind: 'command-start' }
  | { kind: 'command-executed' }
  | { kind: 'command-finished'; exitCode: number | null }
  | { kind: 'command-line'; command: string; trusted: boolean }
  | { kind: 'cwd'; cwd: string };

/**
 * A mark and where its escape sequence sits in the chunk it was completed in:
 * `start` is the index of its ESC (NEGATIVE when the sequence began in an
 * earlier chunk — that many bytes of it were in the previous chunks), `end`
 * the index just past its terminator.
 */
export interface LocatedShellMark {
  mark: ShellMark;
  start: number;
  end: number;
}

const ESC = 0x1b;
const BEL = 0x07;
/** An OSC longer than this is not one of ours (a 633;E of a pasted script is the longest we expect). */
export const SHELL_MARK_MAX_BYTES = 32 * 1024;
export const SHELL_COMMAND_MAX_CHARS = 4_096;

/** Undo the scripts' escaping: `\\` → `\`, `\xNN` → the byte. */
export function unescapeOsc633(value: string): string {
  return value.replace(/\\(\\|x([0-9a-fA-F]{2}))/g, (_m, all: string, hex: string | undefined) =>
    hex ? String.fromCharCode(Number.parseInt(hex, 16)) : all,
  );
}

/** A command line fit to show and store: no control or bidi-override characters, capped. */
export function sanitizeCommandLine(raw: string): string {
  // Newlines inside a multi-line command survive as newlines; everything else goes.
  // eslint-disable-next-line no-control-regex
  const cleaned = raw.replace(/\r\n?/g, '\n').replace(/[\u0000-\u0009\u000b-\u001f\u007f-\u009f‎‏‪-‮⁦-⁩]/g, '').trim();
  return cleaned.length > SHELL_COMMAND_MAX_CHARS ? `${cleaned.slice(0, SHELL_COMMAND_MAX_CHARS - 1)}…` : cleaned;
}

function sanitizeCwd(raw: string): string | null {
  // eslint-disable-next-line no-control-regex
  if (raw.length === 0 || raw.length > 4096 || /[\u0000-\u001f\u007f]/.test(raw)) return null;
  return isAbsolute(raw) ? raw : null;
}

/** Interpret one OSC payload (between `ESC ]` and the terminator); null if it is not a mark. */
export function interpretOscPayload(payload: string, nonce: string | null): ShellMark | null {
  if (payload.startsWith('133;')) {
    const [, code = '', arg] = payload.split(';');
    switch (code) {
      case 'A': return { kind: 'prompt-start' };
      case 'B': return { kind: 'command-start' };
      case 'C': return { kind: 'command-executed' };
      case 'D': {
        const n = arg !== undefined && /^-?\d{1,4}$/.test(arg) ? Number(arg) : null;
        return { kind: 'command-finished', exitCode: n };
      }
      default: return null;
    }
  }
  if (payload.startsWith('633;E;')) {
    const rest = payload.slice(6);
    const cut = rest.lastIndexOf(';');
    const escaped = cut >= 0 ? rest.slice(0, cut) : rest;
    const given = cut >= 0 ? rest.slice(cut + 1) : '';
    const trusted = nonce !== null && nonce.length > 0 && given === nonce;
    return { kind: 'command-line', command: sanitizeCommandLine(unescapeOsc633(escaped)), trusted };
  }
  if (payload.startsWith('633;P;Cwd=')) {
    const cwd = sanitizeCwd(unescapeOsc633(payload.slice(10)));
    return cwd ? { kind: 'cwd', cwd } : null;
  }
  if (payload.startsWith('7;')) {
    // OSC 7: file://host/percent-encoded/path
    const m = /^7;file:\/\/[^/]*(\/.*)$/.exec(payload);
    if (!m) return null;
    let path: string;
    try {
      path = decodeURIComponent(m[1]!);
    } catch {
      return null;
    }
    const cwd = sanitizeCwd(path);
    return cwd ? { kind: 'cwd', cwd } : null;
  }
  return null;
}

/**
 * Incremental OSC scanner for the marks above. Output arrives in arbitrary
 * chunks, so a sequence may straddle them; only the bytes of an OPEN OSC are
 * kept, and one past SHELL_MARK_MAX_BYTES is abandoned.
 */
export function createShellMarkParser(nonce: string | null): { feed(chunk: Uint8Array): LocatedShellMark[] } {
  // 0 ground, 1 saw ESC, 2 in OSC, 3 in OSC and saw ESC, 4 ignoring a runaway OSC
  let state = 0;
  let buf: number[] = [];
  /** Bytes of the open sequence that arrived in earlier chunks. */
  let carried = 0;
  let seqStart = 0;
  const decoder = new TextDecoder('utf-8', { fatal: false });
  return {
    feed(chunk) {
      const out: LocatedShellMark[] = [];
      const finish = (end: number) => {
        const payload = decoder.decode(new Uint8Array(buf));
        const mark = interpretOscPayload(payload, nonce);
        if (mark) out.push({ mark, start: seqStart, end });
        buf = [];
        state = 0;
      };
      if (state !== 0) seqStart = -carried;
      for (let i = 0; i < chunk.length; i++) {
        const byte = chunk[i]!;
        switch (state) {
          case 0:
            if (byte === ESC) { state = 1; seqStart = i; }
            break;
          case 1:
            if (byte === 0x5d /* ] */) { state = 2; buf = []; } else if (byte === ESC) { seqStart = i; } else state = 0;
            break;
          case 2:
            if (byte === BEL) finish(i + 1);
            else if (byte === ESC) state = 3;
            else if (buf.length < SHELL_MARK_MAX_BYTES) buf.push(byte);
            else { state = 4; buf = []; }
            break;
          case 3:
            if (byte === 0x5c /* \ */) finish(i + 1);
            else if (byte === 0x5d) { state = 2; buf = []; seqStart = i - 1; } // ESC ] again: a new OSC
            else { state = byte === ESC ? 1 : 0; buf = []; if (byte === ESC) seqStart = i; }
            break;
          case 4:
            if (byte === BEL) state = 0;
            else if (byte === ESC) { state = 1; seqStart = i; }
            break;
        }
      }
      // What of an open sequence is in THIS chunk counts toward the next chunk's negative start.
      carried = state === 0 || state === 4 ? 0 : (seqStart >= 0 ? chunk.length - seqStart : carried + chunk.length);
      return out;
    },
  };
}
