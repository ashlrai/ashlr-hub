/**
 * core/verse/shell-integration.ts — command blocks for the Terminal (3.15).
 *
 * WHAT. A terminal tab's shell learns to MARK its own output: where the
 * prompt starts (OSC 133;A), where the typed command starts (133;B), where
 * it began executing (133;C), and where it finished with which exit status
 * (133;D;<n>). It also reports the command line as typed (OSC 633;E, the
 * VS Code convention) and its working directory (OSC 633;P;Cwd=…). The
 * Terminal manager cuts the byte stream at those marks into BLOCKS
 * (terminal-blocks.ts): one command, its duration, its exit code, its output.
 *
 * HOW, WITHOUT TOUCHING YOUR DOTFILES. Nothing is written to ~/.zshrc and
 * friends, and nothing is ever appended to a file the operator owns. Instead
 * each supported shell is STARTED so it reads a small script of ours, which
 * first loads the operator's own startup files exactly as the shell would
 * have, then installs the hooks:
 *
 *   zsh  — `ZDOTDIR` points at our directory. Its .zshenv/.zprofile/.zshrc/
 *          .zlogin source YOUR files from your real ZDOTDIR (or $HOME), with
 *          ZDOTDIR set back to yours while they run, then restore ZDOTDIR
 *          (or unset it) for good once startup is over. Argv is unchanged
 *          (`zsh -l`).
 *   bash — `bash --init-file <ours>` (an interactive shell reads it INSTEAD
 *          of ~/.bashrc). It sources /etc/profile and the first of
 *          ~/.bash_profile, ~/.bash_login, ~/.profile — what `bash -l`
 *          reads — then hooks PROMPT_COMMAND and a DEBUG trap (or
 *          bash-preexec's arrays when that is installed; never over a DEBUG
 *          trap someone else owns).
 *   fish — `fish -l --init-command 'source <ours>'`: fish reads its config
 *          as usual, then ours adds event handlers.
 *   anything else (sh, ksh, dash, nu…) — started exactly as before, no blocks.
 *
 * The scripts live in a per-user directory under the OS temp dir (macOS'
 * $TMPDIR is already private to the user), created 0700, refused if it is a
 * symlink or not ours — a shared /tmp on Linux must not let another user
 * plant code our shells would source. They are regenerated (atomically) if
 * missing, since the OS may clean temp files.
 *
 * FORGERY. Any program can print OSC 133 — `cat` a file that contains one
 * and a fake block boundary appears. That only mis-draws a block. The
 * command LINE is different (it is what "Explain this error" sends to a
 * chat), so 633;E carries a per-tab nonce the shell reads from
 * ASHLR_SHELL_NONCE and immediately unsets; an E without it is ignored.
 */
import { randomBytes } from 'node:crypto';
import { lstat, mkdir, rename, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { basename, isAbsolute, join } from 'node:path';

/** Bump when a script changes: a new directory, so a running shell's files are never edited under it. */
export const SHELL_INTEGRATION_VERSION = 1;

export type IntegratedShell = 'zsh' | 'bash' | 'fish';

export function integratedShellKind(shellPath: string): IntegratedShell | null {
  const name = basename(shellPath);
  if (name === 'zsh' || name === 'bash' || name === 'fish') return name;
  return null;
}

