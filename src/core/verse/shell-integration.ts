const HEADER = (shell: string) => `# Ashlr Verse — shell integration for ${shell} (v${SHELL_INTEGRATION_VERSION}).
# Generated by Ashlr; safe to delete (it is recreated when needed).
# It loads YOUR startup files unchanged, then marks prompts and commands with
# OSC 133 / OSC 633 so the Verse terminal can show each command as a block.
# Nothing here writes to your dotfiles.
`;

/** zsh: the four startup files of our ZDOTDIR, plus the hook script they end with. */
export function zshIntegrationFiles(): Record<string, string> {
  const sourceUser = (file: string) => `if [[ -f "$__ashlr_user_zdotdir/${file}" ]]; then
  ZDOTDIR="$__ashlr_user_zdotdir"
  builtin source "$__ashlr_user_zdotdir/${file}"
  if [[ "$ZDOTDIR" != "$__ashlr_user_zdotdir" ]]; then
    __ashlr_user_zdotdir="$ZDOTDIR"
    __ashlr_user_zdotdir_set=1
  fi
  ZDOTDIR="$__ashlr_si_dir"
fi
`;
  return {
    '.zshenv': `${HEADER('zsh')}
typeset -g __ashlr_si_dir="$ZDOTDIR"
if [[ -n "\${ASHLR_USER_ZDOTDIR+x}" ]]; then
  typeset -g __ashlr_user_zdotdir="$ASHLR_USER_ZDOTDIR"
  typeset -gi __ashlr_user_zdotdir_set=1
else
  typeset -g __ashlr_user_zdotdir="$HOME"
  typeset -gi __ashlr_user_zdotdir_set=0
fi
builtin unset ASHLR_USER_ZDOTDIR
__ashlr_restore_zdotdir() {
  if (( __ashlr_user_zdotdir_set )); then
    builtin export ZDOTDIR="$__ashlr_user_zdotdir"
  else
    builtin unset ZDOTDIR
  fi
  builtin unset -f __ashlr_restore_zdotdir
}
${sourceUser('.zshenv')}`,
    '.zprofile': `${HEADER('zsh')}
${sourceUser('.zprofile')}`,
    '.zshrc': `${HEADER('zsh')}
${sourceUser('.zshrc')}
builtin source "$__ashlr_si_dir/ashlr-integration.zsh"
# A non-login shell reads no .zlogin: give ZDOTDIR back now.
if [[ ! -o login ]] && (( $+functions[__ashlr_restore_zdotdir] )); then __ashlr_restore_zdotdir; fi
`,
    '.zlogin': `${HEADER('zsh')}
${sourceUser('.zlogin')}
if (( $+functions[__ashlr_restore_zdotdir] )); then __ashlr_restore_zdotdir; fi
`,
    'ashlr-integration.zsh': `${HEADER('zsh')}
if [[ -n "\${__ashlr_si_loaded-}" || ! -o interactive ]]; then builtin return 0; fi
typeset -g __ashlr_si_loaded=1
typeset -g __ashlr_nonce="\${ASHLR_SHELL_NONCE-}"
builtin unset ASHLR_SHELL_NONCE
typeset -gi __ashlr_in_command=0
typeset -gi __ashlr_status=0

# OSC 633 escaping: backslash, ';' and control characters as \\xNN.
__ashlr_esc() {
  builtin local s="$1"
  s="\${s//\\\\/\\\\\\\\}"
  s="\${s//;/\\\\x3b}"
  s="\${s//$'\\n'/\\\\x0a}"
  s="\${s//$'\\r'/\\\\x0d}"
  s="\${s//$'\\e'/\\\\x1b}"
  s="\${s//$'\\a'/\\\\x07}"
  REPLY="$s"
}

# Runs FIRST among the precmd hooks, so $? is still the command's status.
__ashlr_status_hook() { __ashlr_status=$? }

# Runs LAST, after any prompt theme has rebuilt PS1.
__ashlr_precmd() {
  if (( __ashlr_in_command )); then
    builtin printf '\\033]133;D;%s\\007' "$__ashlr_status"
    __ashlr_in_command=0
  fi
  __ashlr_esc "$PWD"
  builtin printf '\\033]633;P;Cwd=%s\\007' "$REPLY"
  if [[ "$PS1" != *$'\\e]133;B\\a'* ]]; then
    PS1=$'%{\\e]133;A\\a%}'"$PS1"$'%{\\e]133;B\\a%}'
  fi
}

__ashlr_preexec() {
  __ashlr_esc "$1"
  builtin printf '\\033]633;E;%s;%s\\007' "$REPLY" "$__ashlr_nonce"
  builtin printf '\\033]133;C\\007'
  __ashlr_in_command=1
}

precmd_functions=(__ashlr_status_hook \${precmd_functions[@]} __ashlr_precmd)
preexec_functions+=(__ashlr_preexec)
`,
  };
}

/** bash: one --init-file that stands in for a login shell's startup, then hooks. */
export function bashIntegrationScript(): string {
  return `${HEADER('bash')}
if [ -n "\${__ashlr_si_loaded-}" ]; then return 0 2>/dev/null; fi
__ashlr_si_loaded=1

# What \`bash -l\` reads (--init-file replaces it).
if [ -r /etc/profile ]; then . /etc/profile; fi
if [ -r "$HOME/.bash_profile" ]; then . "$HOME/.bash_profile"
elif [ -r "$HOME/.bash_login" ]; then . "$HOME/.bash_login"
elif [ -r "$HOME/.profile" ]; then . "$HOME/.profile"
fi

case $- in *i*) ;; *) return 0 2>/dev/null ;; esac

__ashlr_nonce="\${ASHLR_SHELL_NONCE-}"
unset ASHLR_SHELL_NONCE
__ashlr_in_command=0
__ashlr_at_prompt=0
__ashlr_status=0
__ashlr_last_hist=

__ashlr_esc() {
  local s="$1"
  s="\${s//\\\\/\\\\\\\\}"
  s="\${s//;/\\\\x3b}"
  s="\${s//$'\\n'/\\\\x0a}"
  s="\${s//$'\\r'/\\\\x0d}"
  s="\${s//$'\\e'/\\\\x1b}"
  s="\${s//$'\\a'/\\\\x07}"
  __ashlr_reply="$s"
}

__ashlr_precmd() {
  if [ "$__ashlr_in_command" = 1 ]; then
    builtin printf '\\033]133;D;%s\\007' "$__ashlr_status"
    __ashlr_in_command=0
  fi
  __ashlr_esc "$PWD"
  builtin printf '\\033]633;P;Cwd=%s\\007' "$__ashlr_reply"
  case "$PS1" in
    *'133;B'*) ;;
    *) PS1='\\[\\033]133;A\\007\\]'"$PS1"'\\[\\033]133;B\\007\\]' ;;
  esac
  __ashlr_at_prompt=1
}

__ashlr_command_started() {
  __ashlr_esc "$1"
  builtin printf '\\033]633;E;%s;%s\\007' "$__ashlr_reply" "$__ashlr_nonce"
  builtin printf '\\033]133;C\\007'
  __ashlr_in_command=1
}

# DEBUG trap: the first simple command after a prompt is the command line.
__ashlr_preexec() {
  [ "$__ashlr_at_prompt" = 1 ] || return 0
  __ashlr_at_prompt=0
  local line num cmd="$BASH_COMMAND"
  line="$(HISTTIMEFORMAT= builtin history 1 2>/dev/null)"
  if [[ $line =~ ^[[:space:]]*([0-9]+)[*]?[[:space:]]+(.*)$ ]]; then
    num="\${BASH_REMATCH[1]}"
    if [ "$num" != "$__ashlr_last_hist" ]; then cmd="\${BASH_REMATCH[2]}"; __ashlr_last_hist="$num"; fi
  fi
  __ashlr_command_started "$cmd"
}

__ashlr_precmd_bp() { __ashlr_status=$?; __ashlr_precmd; }
__ashlr_preexec_bp() { __ashlr_command_started "$1"; }

if [ -n "\${bash_preexec_imported-}\${__bp_imported-}" ]; then
  # bash-preexec owns the DEBUG trap and PROMPT_COMMAND: join its arrays.
  precmd_functions+=(__ashlr_precmd_bp)
  preexec_functions+=(__ashlr_preexec_bp)
else
  if declare -p PROMPT_COMMAND 2>/dev/null | grep -q '^declare -a'; then
    PROMPT_COMMAND=('__ashlr_status=$?' "\${PROMPT_COMMAND[@]}" '__ashlr_precmd')
  else
    __ashlr_user_pc="\${PROMPT_COMMAND-}"
    while [[ "$__ashlr_user_pc" =~ ^(.*)[[:space:]\\;]$ ]]; do __ashlr_user_pc="\${BASH_REMATCH[1]}"; done
    PROMPT_COMMAND='__ashlr_status=$?; '"\${__ashlr_user_pc:+$__ashlr_user_pc; }"'__ashlr_precmd'
    unset __ashlr_user_pc
  fi
  # Someone else's DEBUG trap is left alone: prompts are still marked, commands are not.
  if [ -z "$(trap -p DEBUG)" ]; then trap '__ashlr_preexec' DEBUG; fi
fi
`;
}

/** fish: event handlers, loaded after the operator's config by --init-command. */
export function fishIntegrationScript(): string {
  return `${HEADER('fish')}
if set -q __ashlr_si_loaded; or not status is-interactive
  exit 0
end
set -g __ashlr_si_loaded 1
set -g __ashlr_nonce "$ASHLR_SHELL_NONCE"
set -e ASHLR_SHELL_NONCE
set -g __ashlr_in_command 0

function __ashlr_esc
  string join \\n -- $argv | string replace -a '\\\\' '\\\\\\\\' | string replace -a ';' '\\\\x3b' | string replace -a \\e '\\\\x1b' | string replace -a \\a '\\\\x07' | string replace -a \\r '\\\\x0d' | string join '\\\\x0a'
end

function __ashlr_preexec --on-event fish_preexec
  printf '\\033]633;E;%s;%s\\007' (__ashlr_esc $argv) $__ashlr_nonce
  printf '\\033]133;C\\007'
  set -g __ashlr_in_command 1
end

function __ashlr_postexec --on-event fish_postexec
  set -l s $status
  if test "$__ashlr_in_command" = 1
    printf '\\033]133;D;%s\\007' $s
    set -g __ashlr_in_command 0
  end
end

function __ashlr_prompt_start --on-event fish_prompt
  printf '\\033]633;P;Cwd=%s\\007' (__ashlr_esc $PWD)
  printf '\\033]133;A\\007'
end

if functions -q fish_prompt
  functions -c fish_prompt __ashlr_user_fish_prompt
  function fish_prompt
    __ashlr_user_fish_prompt
    printf '\\033]133;B\\007'
  end
end
`;
}

