import * as path from 'node:path';

const DISPOSABLE_TASK_NAME = /^AshlrM93Integration-[a-f0-9-]{1,72}$/;
const MAX_WINDOWS_TASK_XML_BYTES = 256 * 1024;
const MAX_WINDOWS_TASK_SECURITY_DESCRIPTOR_BYTES = 64 * 1024;

function assertSupportedTaskName(taskName: string): void {
  if (taskName !== 'AshlrDaemon' && !DISPOSABLE_TASK_NAME.test(taskName)) {
    throw new Error('unsupported Task Scheduler task name');
  }
}

export function windowsPowerShellPath(
  environment: NodeJS.ProcessEnv = process.env,
): string {
  const systemRoot = environment.SystemRoot ?? environment.WINDIR ?? String.raw`C:\Windows`;
  const normalizedRoot = path.win32.normalize(systemRoot);
  if (
    !/^[A-Za-z]:\\/.test(normalizedRoot) ||
    normalizedRoot.includes('\0') ||
    path.win32.resolve(normalizedRoot) !== normalizedRoot
  ) {
    throw new Error('Windows SystemRoot is not a canonical local absolute path');
  }
  return path.win32.join(
    normalizedRoot,
    'System32',
    'WindowsPowerShell',
    'v1.0',
    'powershell.exe',
  );
}

