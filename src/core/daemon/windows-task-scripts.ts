    "$principal=$definition.Principal",
    "$principal.Id='AshlrPrincipal'",
    '$principal.UserId=$current.Name',
    '$principal.LogonType=3',
    '$principal.RunLevel=0',
    '$trigger=$definition.Triggers.Create(9)',
    '$trigger.Enabled=$true',
    '$trigger.UserId=$current.Name',
    "$trigger.ExecutionTimeLimit='PT0S'",
    '$action=$definition.Actions.Create(0)',
    '$action.Path=$expectedLauncher',
    "$definition.Actions.Context='AshlrPrincipal'",
    '$settings=$definition.Settings',
    '$settings.AllowDemandStart=$true',
    '$settings.MultipleInstances=2',
    '$settings.DisallowStartIfOnBatteries=$false',
    '$settings.StopIfGoingOnBatteries=$false',
    '$settings.AllowHardTerminate=$true',
    '$settings.StartWhenAvailable=$false',
